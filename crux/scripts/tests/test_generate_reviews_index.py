class CarriageReturnLaneTestCase(_Harness):
    """[SECURITY:S1] A lone `\r` in a report reaches the grammar as itself.

    The reader used `read_text(encoding="utf-8")`, whose universal-newline
    translation rewrote a lone `\r` to `\n` BEFORE any grammar saw the text.
    The locator grammar excludes `\r`, so the exclusion was unreachable from
    the CLI: one carriage return inside a table cell split the row into two
    lines the author never wrote. Four consequences, one lane each below —
    a `..` traversal hidden, a second lifecycle record forged, `LOCATOR_LIMIT`
    halved, and a displayed row disguised. `\r\n` is a LINE ENDING, not a
    payload, so the control asserts a CRLF report renders the same index as
    its LF twin.
    """

    #: One finding and one `resolved` record naming a real surface. Every
    #: hostile shape below is this report with a `\r` spliced into the record
    #: row, and the control is this report with CRLF endings.
    def base(self) -> str:
        return _lifecycle(
            "2026-09-09", findings=["adr-review-alpha"],
            records=[("2026-09-09", "adr-review-alpha", 1, "resolved",
                      "bionic")])

    def setUp(self) -> None:
        super().setUp()
        self.index = self.reviews / "index.md"
        self.index.write_text(EMPTY_INDEX, encoding="utf-8")
        self.before = self.index.read_bytes()

    def write_raw(self, name: str, text: str) -> None:
        """The report, written with newline translation OFF.

        `Path.write_text` would translate on a platform whose `os.linesep` is
        not `\n`; these fixtures are about the exact bytes.
        """
        with open(self.reviews / name, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)

    def row_line(self, text: str) -> int:
        """The 1-based line the record row occupies in the LF text."""
        for number, line in enumerate(text.split("\n"), start=1):
            if line.startswith("| 2026-09-09 | `adr-review-alpha` |"):
                return number
        raise AssertionError("no record row in the fixture")

    def refuse(self, text: str) -> str:
        self.write_raw("2026-09-09.md", text)
        result = self.run_cli("--today", "2026-12-31")
        self.assertEqual(result.returncode, 1, (result.stdout, result.stderr))
        self.assertNotIn("Traceback", result.stderr)
        self.assertEqual(self.index.read_bytes(), self.before)
        return json.loads(result.stdout)["validation_errors"][0]["error"]

    def test_a_cr_hiding_a_traversal_in_a_resolved_locator_is_refused(self):
        base = self.base()
        error = self.refuse(base.replace(
            "| 1 | resolved | bionic |",
            "| 1 | resolved | bionic\r/../../etc/CANARY |"))
        self.assertIn("outside the locator grammar", error)
        self.assertIn(f"at line {self.row_line(base)}", error)

    def test_a_cr_forging_a_second_lifecycle_record_is_refused(self):
        base = self.base()
        error = self.refuse(base.replace(
            "| 2026-09-09 | `adr-review-alpha` | 1 | resolved | bionic |",
            "| 2026-09-09 | `adr-review-alpha` | 1 | resolved | x"
            "\r| 2026-09-09 | `adr-review-alpha` | 2 | resolved | bionic |"))
        # A `\r` that glues two COMPLETE rows makes one line carrying both
        # rows' cells, and the cell-count refusal is the one that fires. It
        # names the same line and takes the same exit-1 document lane; before
        # the fix this line was two rows and the second one counted.
        self.assertIn("a record row carries 5 cells", error)
        self.assertIn(f"at line {self.row_line(base)}", error)

    def test_a_cr_splitting_an_overlong_locator_under_the_bound_is_refused(self):
        """300 characters, halved by the `\r` into two 150s under the bound."""
        base = self.base()
        error = self.refuse(base.replace(
            "| 1 | resolved | bionic |",
            "| 1 | resolved | " + "a" * 150 + "\r" + "b" * 150 + " |"))
        self.assertIn("outside the locator grammar", error)
        self.assertIn(f"at line {self.row_line(base)}", error)

    def test_a_cr_disguising_which_row_a_terminal_shows_is_refused(self):
        base = self.base()
        error = self.refuse(base.replace(
            "| 2026-09-09 | `adr-review-alpha` | 1 | resolved | bionic |",
            "| 2026-09-09 | `adr-review-alpha` | 2 | resolved | bionic |"
            "\r| 2026-09-09 | `adr-review-alpha` | 1 | resolved | x   |"))
        # A `\r` that glues two COMPLETE rows makes one line carrying both
        # rows' cells, and the cell-count refusal is the one that fires. It
        # names the same line and takes the same exit-1 document lane; before
        # the fix this line was two rows and the second one counted.
        self.assertIn("a record row carries 5 cells", error)
        self.assertIn(f"at line {self.row_line(base)}", error)

    def two_row_pair(self) -> tuple[str, str]:
        """A two-record report, and the same report with the `\r` for the `\n`.

        The carriage return is the ONLY difference between the two, so the
        refusal below is a property of that byte rather than of the two rows.
        """
        text = _lifecycle(
            "2026-09-09", findings=["adr-review-alpha", "adr-review-beta"],
            records=[("2026-09-09", "adr-review-alpha", 1, "resolved", "bionic"),
                     ("2026-09-09", "adr-review-beta", 1, "resolved", "bionic")])
        joined = ("| 2026-09-09 | `adr-review-alpha` | 1 | resolved | bionic |\n"
                  "| 2026-09-09 | `adr-review-beta` | 1 | resolved | bionic |")
        assert joined in text
        return text, text.replace(joined, joined.replace("\n", "\r"))

    def test_two_real_rows_joined_by_a_cr_are_refused(self):
        honest, hostile = self.two_row_pair()
        error = self.refuse(hostile)
        # A `\r` that glues two COMPLETE rows makes one line carrying both
        # rows' cells, and the cell-count refusal is the one that fires. It
        # names the same line and takes the same exit-1 document lane; before
        # the fix this line was two rows and the second one counted.
        self.assertIn("a record row carries 5 cells", error)
        self.assertIn(f"at line {self.row_line(honest)}", error)

    def test_two_real_rows_joined_by_a_newline_are_the_control(self):
        honest, _ = self.two_row_pair()
        self.write_raw("2026-09-09.md", honest)
        result = self.run_cli("--today", "2026-12-31")
        self.assertEqual(result.returncode, 0, (result.stdout, result.stderr))
        self.assertNotEqual(self.index.read_bytes(), self.before)

    def test_a_crlf_report_renders_the_same_index_as_its_lf_twin(self):
        """`\r\n` is a line ending: it parses, and it parses to the same thing."""
        base = self.base()
        self.write_raw("2026-09-09.md", base)
        self.assertEqual(self.run_cli("--today", "2026-12-31").returncode, 0)
        lf_index = self.index.read_bytes()
        self.index.write_bytes(self.before)
        self.write_raw("2026-09-09.md", base.replace("\n", "\r\n"))
        result = self.run_cli("--today", "2026-12-31")
        self.assertEqual(result.returncode, 0, (result.stdout, result.stderr))
        self.assertEqual(self.index.read_bytes(), lf_index)


def _assessed(date: str, *, row: tuple, entry: str) -> str:
    """A lifecycle report assessing one part of OBJ-1.

    `row` is the seven-column assessment row; `entry` is the part's
    `measured_objectives` body, or `""` for a report carrying no key. No
    findings and no lifecycle records — the corpus exercises the cross-date
    carryover check, not the standing arc.
    """
    key = f"measured_objectives:\n{entry}" if entry else ""
    return (
        f"---\ntype: adr-review\ndate: {date}\nreport_grammar: lifecycle\n"
        f"dismissed: []\n{key}---\n\n"
        f"# Decision review \u2014 {date}\n\n"
        "| finding id | section | objective | proposed act | size |\n"
        "|---|---|---|---|---|\n\n"
        "## Propose\n\n## Amend\n\n## Repair\n\n## Revoke\n\n"
        "## Keep\n\n## Coverage\n\n"
        "| objective | measure | evidence | locator | domains | "
        "conclusion | findings |\n"
        "|---|---|---|---|---|---|---|\n"
        "| " + " | ".join(str(c) for c in row) + " |\n")


# The part is blocked on the first date, so it MUST carry an entry there; it
# discriminates on the second, so `validate_structure` alone accepts the
# second report with the entry dropped. Only the cross-date check refuses it.
_BLOCKED = ("OBJ-1", "OBJ-1.1 \u2014 a claim", "unavailable", "a/p.md", "d",
            "inconclusive", "\u2014")
_MEASURED = ("OBJ-1", "OBJ-1.1 \u2014 a claim", "resolved", "a/p.md", "d",
             "gap", "\u2014")
_BLOCKED_ENTRY = ("  - objective: OBJ-1\n    part: OBJ-1.1\n"
                  "    outcome: attempted\n    measure_digest: sha256:same\n"
                  "    blocker: no baseline\n")
_MEASURED_ENTRY = ("  - objective: OBJ-1\n    part: OBJ-1.1\n"
                   "    outcome: measured\n    measure_digest: sha256:same\n"
                   "    evidence: a/p.md\n")


class PartCarryoverLaneTestCase(_Harness):
    """The corpus pass runs `check_part_carryover`, not just `validate_structure`.

    The module's own tests pin the check's behavior; these pin that the
    regenerator CALLS it. Remove the call and the first test exits 0.
    """

    def test_dropping_a_carried_part_entry_refuses_through_the_cli(self):
        self.write("2026-09-09.md",
                   _assessed("2026-09-09", row=_BLOCKED, entry=_BLOCKED_ENTRY))
        self.write("2026-09-10.md",
                   _assessed("2026-09-10", row=_MEASURED, entry=""))
        proc = self.run_cli("--dry-run")
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)
        self.assertIn("carried a part-level", proc.stdout)

    def test_carrying_it_forward_is_the_control(self):
        self.write("2026-09-09.md",
                   _assessed("2026-09-09", row=_BLOCKED, entry=_BLOCKED_ENTRY))
        self.write("2026-09-10.md",
                   _assessed("2026-09-10", row=_MEASURED, entry=_MEASURED_ENTRY))
        proc = self.run_cli("--dry-run")
        # `--dry-run` exits 1 on DRIFT here (the fixture repo has no index
        # yet), so the control reads the validation lane, not the exit code.
        self.assertNotIn("validation_errors", proc.stdout)
        self.assertNotIn("carried a part-level", proc.stdout)

class WriterLaneTestCase(_Harness):
    """The WRITE side's environment lane: the index cannot be created."""

    def test_an_unwritable_reviews_directory_is_an_environment_error(self):
        if hasattr(os, "geteuid") and os.geteuid() == 0:
            self.skipTest("running as root: a 0o555 directory is still writable")
        self.write("2026-09-07.md", _report("2026-09-07", ["adr-review-a"], []))
        self.reviews.chmod(0o555)
        self.addCleanup(self.reviews.chmod, 0o755)
