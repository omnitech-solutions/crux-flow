class AtomicWriteBackstopTestCase(unittest.TestCase):
    """`_atomic_write_text`'s own guards, which the walk preempts on the CLI.

    Driven directly BECAUSE they are a backstop: `collect` refuses a symlinked
    entry and `_contained` refuses a symlinked directory, so no CLI input
    reaches these checks in one pass. They cover the window between the walk
    and the write. The CLI-reachable refusals are asserted by
    `ContainmentTestCase` above, so this class is not the file's only coverage
    of the guard.
    """

    def setUp(self) -> None:
        spec = importlib.util.spec_from_file_location("_reviews_index", SCRIPT)
        self.mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(self.mod)
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.tree = Path(self._tmp.name) / "tree"
        self.tree.mkdir()

    def test_a_symlinked_target_is_refused_and_the_victim_survives(self):
        victim = Path(self._tmp.name) / "victim.md"
        victim.write_text("UNTOUCHED\n", encoding="utf-8")
        target = self.tree / "index.md"
        target.symlink_to(victim)
        with self.assertRaises(OSError) as caught:
            self.mod._atomic_write_text(target, "NEW\n", contained_under=self.tree)
        self.assertIn("is a symlink", str(caught.exception))
        self.assertEqual(victim.read_text(encoding="utf-8"), "UNTOUCHED\n")

        # PAIRED POSITIVE CONTROL: the same call to a real path writes.
        target.unlink()
        self.mod._atomic_write_text(target, "NEW\n", contained_under=self.tree)
        self.assertEqual(target.read_text(encoding="utf-8"), "NEW\n")

    def test_a_parent_resolving_outside_the_tree_is_refused(self):
        outside = Path(self._tmp.name) / "outside"
        outside.mkdir()
        link = self.tree / "linked"
        link.symlink_to(outside, target_is_directory=True)
        with self.assertRaises(OSError) as caught:
            self.mod._atomic_write_text(link / "index.md", "NEW\n",
                                        contained_under=self.tree)
        self.assertIn("not contained under", str(caught.exception))
        self.assertFalse((outside / "index.md").exists())

        # PAIRED POSITIVE CONTROL: a real subdirectory of the tree writes.
        real = self.tree / "real"
        real.mkdir()
        self.mod._atomic_write_text(real / "index.md", "NEW\n",
                                    contained_under=self.tree)
        self.assertEqual((real / "index.md").read_text(encoding="utf-8"), "NEW\n")

    def test_a_left_over_temporary_file_is_refused_rather_than_clobbered(self):
        target = self.tree / "index.md"
        (self.tree / "index.md.tmp").write_text("SOMEONE ELSE\n", encoding="utf-8")
        with self.assertRaises(OSError) as caught:
            self.mod._atomic_write_text(target, "NEW\n", contained_under=self.tree)
        self.assertIn("already exists", str(caught.exception))
        self.assertEqual((self.tree / "index.md.tmp").read_text(encoding="utf-8"),
                         "SOMEONE ELSE\n")

        # PAIRED POSITIVE CONTROL: with the stale tmp gone the write lands and
        # leaves no tmp behind.
        (self.tree / "index.md.tmp").unlink()
        self.mod._atomic_write_text(target, "NEW\n", contained_under=self.tree)
        self.assertEqual(target.read_text(encoding="utf-8"), "NEW\n")
        self.assertFalse((self.tree / "index.md.tmp").exists())


class LaneTestCase(_Harness):
    """The nine measured filesystem lanes, L1 through L8 plus L4-prime.

    Every lane is a shape a checkout can present at the two directory
    segments (`adrs`, `reviews`) or at the two leaf paths (`index.md`,
    `index.md.tmp`). Eight of the nine were already refused when this class
    was written; L4 and L4-prime were NOT, and that was the defect: a DANGLING
    symlink at a directory segment reads false through `is_dir()`, so the run
    printed `surface_absent` at exit 0 — a silent N/A naming nothing, on a
    checkout whose reviews surface had been redirected.

    Every negative lane asserts three things and not one: the exit lane WITH a
    content discriminator, that the outside target is byte-identical
    afterwards, and that whatever stood at the index path is unchanged. Every
    negative lane also carries a paired positive control repairing exactly the
    one fixture property under test, so "refused" cannot be satisfied by a
    script that refuses everything. Every case drives `main` through the CLI.
    """

    OUTSIDE_BODY = "OUTSIDE TARGET \u2014 must never be written through.\n"

    def setUp(self) -> None:
        super().setUp()
        self.outside = self.root / "outside"
        self.outside.mkdir()
        self.target = self.outside / "target.md"
        self.target.write_text(self.OUTSIDE_BODY, encoding="utf-8")

    # ── state snapshots, so "unchanged" is asserted rather than assumed ──

    def _outside_state(self):
        return self.target.read_bytes() if self.target.exists() else None

    def _index_state(self):
        """What stands at the index path, whatever KIND of thing it is."""
        path = self.reviews / "index.md"
        if path.is_symlink():
            return ("symlink", os.readlink(path))
        if path.is_dir():
            return ("dir", sorted(entry.name for entry in path.iterdir()))
        if path.exists():
            return ("file", path.read_bytes())
        return ("absent", None)

    def _two_reports(self, at: Path | None = None) -> None:
        where = self.reviews if at is None else at
        for date, slug in (("2026-09-07", "one"), ("2026-09-08", "two")):
            (where / f"{date}.md").write_text(
                _report(date, [f"adr-review-{slug}"], []), encoding="utf-8")

    def _assert_document_refusal(self, result, fragment, file_suffix):
        self.assertEqual(result.returncode, 1, result.stdout)
        entry = json.loads(result.stdout)["validation_errors"][0]
        self.assertIn(fragment, entry["error"])
        # L1 and L6 are BOTH "is a symlink" at exit 1. The `file` key is the
        # discriminator that tells the index from its temporary file.
        self.assertTrue(entry["file"].endswith(file_suffix), entry["file"])

    def _assert_environment_refusal(self, result, fragment):
        self.assertEqual(result.returncode, 2, result.stdout)
        self.assertEqual(result.stdout, "")
        self.assertIn(fragment, result.stderr)
        self.assertNotIn("Traceback", result.stderr)

    # ── L1 / L2: the index leaf is a symlink, resolving or not ───────────

    def test_L1_a_symlinked_index_is_refused_and_names_the_index(self):
        self._two_reports()
        (self.reviews / "index.md").symlink_to(self.target)
        before_out, before_idx = self._outside_state(), self._index_state()
        self._assert_document_refusal(self.run_cli(), "is a symlink", "index.md")
        self.assertEqual(self._outside_state(), before_out)
        self.assertEqual(self._index_state(), before_idx)

        # PAIRED POSITIVE CONTROL: the same corpus with a real index writes.
        (self.reviews / "index.md").unlink()
        self.assertEqual(self.run_cli().returncode, 0)
        self.assertEqual(self._outside_state(), before_out)

    def test_L2_a_dangling_symlinked_index_is_refused_the_same_way(self):
        """`is_file()` is false through a dangling link; `is_symlink()` is true."""
        self._two_reports()
        (self.reviews / "index.md").symlink_to(self.outside / "never-created.md")
        before_out, before_idx = self._outside_state(), self._index_state()
        self._assert_document_refusal(self.run_cli(), "is a symlink", "index.md")
        self.assertFalse((self.outside / "never-created.md").exists())
        self.assertEqual(self._outside_state(), before_out)
        self.assertEqual(self._index_state(), before_idx)

        # PAIRED POSITIVE CONTROL: remove the link and the write lands.
        (self.reviews / "index.md").unlink()
        self.assertEqual(self.run_cli().returncode, 0)
        self.assertFalse((self.outside / "never-created.md").exists())

    # ── L3 / L4: the `reviews` segment is a symlink, resolving or not ────

    def test_L3_a_symlinked_reviews_segment_is_refused_by_name(self):
        elsewhere = self.outside / "reviews"
        elsewhere.mkdir()
        self._two_reports(at=elsewhere)
        (elsewhere / "index.md").write_text(self.OUTSIDE_BODY, encoding="utf-8")
        self.reviews.rmdir()
        self.reviews.symlink_to(elsewhere, target_is_directory=True)
        before_out, before_idx = self._outside_state(), self._index_state()
        self._assert_environment_refusal(
            self.run_cli(), "the reviews directory is a symlink")
        self.assertEqual(self._outside_state(), before_out)
        self.assertEqual(self._index_state(), before_idx)
        self.assertEqual((elsewhere / "index.md").read_text(encoding="utf-8"),
                         self.OUTSIDE_BODY)

        # PAIRED POSITIVE CONTROL: the identical corpus as a real directory
        # inside the tree is walked and written.
        self.reviews.unlink()
        shutil.copytree(elsewhere, self.reviews)
        (self.reviews / "index.md").unlink()
        self.assertEqual(self.run_cli().returncode, 0)

    def test_L4_a_DANGLING_symlinked_reviews_segment_is_refused_not_absent(self):
        """THE DEFECT. This read as `surface_absent` at exit 0 before the repair.

        `reviews.is_dir()` is false through a dangling link, so the surface
        left the run through the absent-surface branch — a positive
        discriminator asserting there is no derived artifact, on a checkout
        that had redirected the surface off the tree.
        """
        sentinel = self.outside / "sentinel.md"
        sentinel.write_text(self.OUTSIDE_BODY, encoding="utf-8")
        self.reviews.rmdir()
        self.reviews.symlink_to(self.outside / "never-created",
                                target_is_directory=True)
        before_out, before_idx = self._outside_state(), self._index_state()
        for args in ((), ("--dry-run",)):
            with self.subTest(args=args):
                result = self.run_cli(*args)
                self._assert_environment_refusal(
                    result, "the reviews directory is a symlink")
                # The discriminator that names the defect: NOT the absent
                # surface, which is what this lane used to report.
                self.assertNotIn("surface_absent", result.stdout)
        self.assertEqual(self._outside_state(), before_out)
        self.assertEqual(self._index_state(), before_idx)
        self.assertEqual(sentinel.read_text(encoding="utf-8"), self.OUTSIDE_BODY)
        self.assertFalse((self.outside / "never-created").exists())

        # PAIRED POSITIVE CONTROL A: a genuinely absent surface still reports
        # `surface_absent` at exit 0, so the repair narrowed nothing else.
        self.reviews.unlink()
        absent = self.run_cli("--dry-run")
        self.assertEqual(absent.returncode, 0, absent.stderr)
        self.assertIs(json.loads(absent.stdout)["surface_absent"], True)

        # PAIRED POSITIVE CONTROL B: a real directory at the same path is
        # measured, so the refusal is the link and not the path.
        self.reviews.mkdir(parents=True)
        self.assertEqual(self.run_cli().returncode, 0)

    # ── L4-prime / L5: the `adrs` segment is a symlink, resolving or not ─

    def test_L4prime_a_DANGLING_symlinked_adrs_segment_is_refused_not_absent(self):
        """The same class one segment up. `adrs` is walked before `reviews`."""
        adrs = self.root / "bionic" / "adrs"
        shutil.rmtree(adrs)
        adrs.symlink_to(self.outside / "never-created", target_is_directory=True)
        before_out = self._outside_state()
        for args in ((), ("--dry-run",)):
            with self.subTest(args=args):
                result = self.run_cli(*args)
                self._assert_environment_refusal(
                    result, "the adrs directory is a symlink")
                self.assertNotIn("surface_absent", result.stdout)
        self.assertEqual(self._outside_state(), before_out)
        self.assertFalse((self.outside / "never-created").exists())

        # PAIRED POSITIVE CONTROL: a real `adrs/reviews/` is measured.
        adrs.unlink()
        self.reviews.mkdir(parents=True)
        self.assertEqual(self.run_cli().returncode, 0)

    def test_L5_a_symlinked_adrs_segment_names_adrs_and_not_reviews(self):
        """The diagnostic named the wrong surface: `adrs` is the link here."""
        elsewhere = self.outside / "adrs"
        (elsewhere / "reviews").mkdir(parents=True)
